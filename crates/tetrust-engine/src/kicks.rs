//! SRS 월킥 테이블 (가이드라인 표준, y-up).
//!
//! 각 행의 첫 항목 (0, 0)은 제자리 회전이다. 순서대로 시도해서 처음 들어맞는 오프셋을 쓴다.

use crate::piece::{PieceKind, Rotation};

type Kicks = [(i32, i32); 5];

const JLSTZ: [Kicks; 8] = [
    [(0, 0), (-1, 0), (-1, 1), (0, -2), (-1, -2)], // 0 -> R
    [(0, 0), (1, 0), (1, -1), (0, 2), (1, 2)],     // R -> 0
    [(0, 0), (1, 0), (1, -1), (0, 2), (1, 2)],     // R -> 2
    [(0, 0), (-1, 0), (-1, 1), (0, -2), (-1, -2)], // 2 -> R
    [(0, 0), (1, 0), (1, 1), (0, -2), (1, -2)],    // 2 -> L
    [(0, 0), (-1, 0), (-1, -1), (0, 2), (-1, 2)],  // L -> 2
    [(0, 0), (-1, 0), (-1, -1), (0, 2), (-1, 2)],  // L -> 0
    [(0, 0), (1, 0), (1, 1), (0, -2), (1, -2)],    // 0 -> L
];

const I: [Kicks; 8] = [
    [(0, 0), (-2, 0), (1, 0), (-2, -1), (1, 2)], // 0 -> R
    [(0, 0), (2, 0), (-1, 0), (2, 1), (-1, -2)], // R -> 0
    [(0, 0), (-1, 0), (2, 0), (-1, 2), (2, -1)], // R -> 2
    [(0, 0), (1, 0), (-2, 0), (1, -2), (-2, 1)], // 2 -> R
    [(0, 0), (2, 0), (-1, 0), (2, 1), (-1, -2)], // 2 -> L
    [(0, 0), (-2, 0), (1, 0), (-2, -1), (1, 2)], // L -> 2
    [(0, 0), (1, 0), (-2, 0), (1, -2), (-2, 1)], // L -> 0
    [(0, 0), (-1, 0), (2, 0), (-1, 2), (2, -1)], // 0 -> L
];

fn index(from: Rotation, to: Rotation) -> Option<usize> {
    Some(match (from.0, to.0) {
        (0, 1) => 0,
        (1, 0) => 1,
        (1, 2) => 2,
        (2, 1) => 3,
        (2, 3) => 4,
        (3, 2) => 5,
        (3, 0) => 6,
        (0, 3) => 7,
        _ => return None,
    })
}

/// from -> to 회전에서 시도할 오프셋 목록.
///
/// 180도 회전은 SRS 표준에 킥이 없으므로 제자리 회전만 시도한다.
pub fn kicks(kind: PieceKind, from: Rotation, to: Rotation) -> &'static [(i32, i32)] {
    const NONE: [(i32, i32); 1] = [(0, 0)];
    match (kind, index(from, to)) {
        (PieceKind::O, _) | (_, None) => &NONE,
        (PieceKind::I, Some(i)) => &I[i],
        (_, Some(i)) => &JLSTZ[i],
    }
}
